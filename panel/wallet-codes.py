#!/usr/bin/env python3
"""Draw the donation addresses as QR codes, for the panel's Support page.

Run by hand and commit the result, the same way `lock-deps.sh` is:

    make wallets

A wallet address is the one string in this project that must never be wrong by
a character, so the page that shows it does not hold it. Both the text under
the copy button and the code a phone scans come out of the single table below,
in one pass, and land together in `frontend/src/lib/walletCodes.ts` - which
means the two cannot disagree with each other however either is edited later,
because neither is edited at all. Nothing else in the frontend knows an
address; `lib/wallets.ts` joins these entries to a name and a mark by id, and
an id with no entry here simply does not appear on the page.

The repository README's donation list is filled from the same table in the
same pass, between `wallets:begin`/`wallets:end` markers, so the address a
visitor copies from GitHub and the one the panel shows are one string. The
README gets no QR codes: its fenced blocks give it GitHub's copy button, which
is the same job done the way a web page does it.

Generating at build time rather than serving from the API is deliberate. The
panel's HTTP API is the surface a script automates a VPN server through, and
`tests/test_api_docs.py` holds every route in it to a written description;
"here is where to send money" is not an operation on a server, and adding one
would put it in the OpenAPI document and on the API reference page.

The payload is the bare address, not a `bitcoin:`-style payment URI. Wallets
read both, but a URI is a second string that would have to stay in step with
the one on screen, and a scheme prefix that a particular exchange's scanner
does not know is a deposit that goes nowhere.
"""

import io
import re
import subprocess
from pathlib import Path

import segno

# Error correction M, as apps/accounts/views.py uses for enrolment codes: the
# level every wallet app is tested against, and enough redundancy for a code
# read off a screen at an angle. H would double the size of the Monero symbol
# for a robustness nobody scanning a screen needs.
ERROR_CORRECTION = "m"

OUTPUT = Path(__file__).parent / "frontend/src/lib/walletCodes.ts"
README = Path(__file__).parent.parent / "README.md"

# id -> address. The id is the join key: `frontend/src/lib/wallets.ts` gives
# each one its coin, its chain and the order they are shown in.
