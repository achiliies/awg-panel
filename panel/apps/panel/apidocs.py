"""What this API is, written down where a machine can read it.

Everything the panel does, it does through the HTTP API, and until now the only
description of it was `docs/API.md` - prose, in the repository, on a machine
that is not the one being administered. A script author had nothing to point a
tool at: no import into Postman or Insomnia, no client generator, no way to ask
a running panel what it serves.

So the catalog below is the description, and it is rendered as OpenAPI 3.1 by
`document()`. One source, two readers: `GET api/v1/openapi.json` hands the
document to whatever tooling wants it, and the panel's own API page renders the
same document into the reference an admin reads. Neither can drift from the
other, and `tests/test_api_docs.py` walks the URL map to make sure neither can
drift from the routes either - an endpoint added without an entry here fails the
suite.

Three things are deliberately not attempted.

There are no request or response *schemas*, only examples. A schema per body
would be a second declaration of every serializer in the panel, maintained by
hand, and the first one to fall behind would be worse than no schema at all -
a generated client that compiles and is wrong. Examples come off real responses
and are checked by eye against the same fixtures the tests use.

The prose is English, and it stays English. The panel picks its language in the
browser and never tells the server which one, exactly as `awg/validate.py`'s
parameter catalog does; the UI overrides what it has a translation for, keyed by
operation id, and falls back to what is written here.

And nothing here is generated by introspecting the views. DRF can be made to
guess at paths and status codes, and what it produces is a description of the
framework rather than of the panel: no word about which routes an API token may
not touch, which sweeps are one config rewrite rather than thirty, or why a save
that restarts the web service still answers. Those are the things somebody
automating this actually needs, and they have to be written by a person.
"""

from dataclasses import dataclass

# The three ways a request may prove who it is, as the document names them.
#
# "any" is a token or a session, which is nearly everything. "session" is the
# credential surface - see apps.accounts.permissions for why a token is refused
# there - and "none" is the pair of routes that answer before anybody has signed
# in at all.
AUTH_ANY = "any"
AUTH_SESSION = "session"
AUTH_NONE = "none"

BEARER = "bearerAuth"
COOKIE = "sessionAuth"


@dataclass(frozen=True)
class Param:
    """One query or path parameter, as OpenAPI spells it."""

    name: str
    description: str
    where: str = "query"
    required: bool = False
    kind: str = "string"
    default: object | None = None
    values: tuple[str, ...] = ()

    def render(self) -> dict:
        schema: dict = {"type": self.kind}
        if self.values:
            schema["enum"] = list(self.values)
        if self.default is not None:
            schema["default"] = self.default
        return {
            "name": self.name,
            "in": self.where,
            "required": self.required or self.where == "path",
            "description": self.description,
            "schema": schema,
        }


@dataclass(frozen=True)
class Op:
    """One operation: a method, a path, and everything worth knowing about it."""

    id: str
    method: str
    path: str
    tag: str
    summary: str
    description: str
    params: tuple[Param, ...] = ()
    #: Example request body. None means the operation takes none.
    body: object | None = None
    body_note: str = ""
    body_required: bool = True
    #: What the body is sent as. Only `restore` is not JSON, and the difference
    #: is not cosmetic: a reader shown `-d` for a file upload has been shown a
    #: command that cannot work.
    body_type: str = "application/json"
    #: Example success response. None means the operation answers with no body.
    result: object | None = None
    result_note: str = ""
    result_type: str = "application/json"
    success: str = "200"
    #: Failures worth branching on, beyond the ones every route can return.
    codes: tuple[tuple[str, str], ...] = ()
    auth: str = AUTH_ANY

    def security(self) -> list[dict]:
        if self.auth == AUTH_NONE:
            return []
        if self.auth == AUTH_SESSION:
            return [{COOKIE: []}]
        return [{BEARER: []}, {COOKIE: []}]

    def render(self) -> dict:
        out: dict = {
            "operationId": self.id,
            "tags": [self.tag],
            "summary": self.summary,
            "description": self.description,
            "security": self.security(),
            "responses": self._responses(),
        }
        if self.params:
            out["parameters"] = [param.render() for param in self.params]
        if self.body is not None:
            out["requestBody"] = {
                "required": self.body_required,
                "content": {self.body_type: {"schema": self._body_schema(), "example": self.body}},
            }
            if self.body_note:
                out["requestBody"]["description"] = self.body_note
        return out

    def _body_schema(self) -> dict:
        """An object, unless the body is a file - which a generator has to know."""
        if self.body_type == "multipart/form-data":
            return {
                "type": "object",
                "properties": {"file": {"type": "string", "format": "binary"}},
                "required": ["file"],
            }
        return {"type": "object"}

    def _responses(self) -> dict:
        ok: dict = {"description": self.result_note or _SUCCESS_WORDS.get(self.success, "Success.")}
        if self.result is not None:
            schema = (
                {"type": "string"} if self.result_type.startswith("text/") else {"type": "object"}
            )
            if self.result_type in {"image/png", "application/zip", "application/gzip"}:
                schema = {"type": "string", "format": "binary"}
            content: dict = {"schema": schema}
            # A binary body has no example worth printing; the description says
            # what it is instead.
            if schema.get("format") != "binary":
                content["example"] = self.result
            ok["content"] = {self.result_type: content}
        out = {self.success: ok}
        for code, note in self.codes:
            out[code] = {"description": note}
        return out


_SUCCESS_WORDS = {
    "200": "The current state.",
    "201": "Created.",
    "204": "Done. No body.",
}


