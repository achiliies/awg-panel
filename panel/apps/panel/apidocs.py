# The conventions, for whoever opens the document in a tool rather than in the
# panel. The page renders its own version of this from the UI catalog, in the
# admin's own language; this copy is what a generated client's README gets.
DESCRIPTION = """\
Everything the AWG Panel does, it does through this API: the panel's own
interface is a client of it, and nothing here is reserved for that client.

**Base path.** Every route is served under the panel's secret base path, which
is already in `servers` below. Anything outside it returns a bare 404, so a
scanner learns nothing.

**Authentication.** Either an API token in an `Authorization: Bearer awgp_...`
header, or the session cookie a browser gets from `POST auth/login`. Anything
that is not a browser should use a token: no cookie jar, no CSRF token, no
second factor, and it can be revoked on its own. A token authenticates as the
account and may do everything the panel can **except** touch the credentials
that authorise it - every route tagged Credentials, plus `auth/logout` and
`POST restore`, answers 403 to one. `GET backup` is the limit of that rule and
not an exception to it: the archive carries the session table, so anything that
can download one can sign in as the account. See that operation.

**CSRF.** A mutating request made with the session cookie must carry
`X-CSRFToken` matching the `awgcsrftoken` cookie; `GET auth/session` sets it. A
request authenticated by a bearer token needs none, because nothing can make a
browser attach an `Authorization` header it was not given.

**Case.** JSON is camelCase in both directions. Times are RFC 3339 in UTC
unless the field name ends in a unit, in which case it is a Unix timestamp in
seconds - `lastHandshake` is what the kernel reports.

**Errors.** Always `{"detail": "...", "errors": {"field": "..."}}`, plus a
`code` where a caller needs to branch on the reason rather than the wording.
`503` with `code: "not_configured"` is what every config-reading route answers
where there is no server configuration: an expected state rather than a fault.
`409` with `code: "name_in_use"` is the conflict that is about a name; a `409`
without it says the tunnel subnet has no free address left, which retrying under
another name will never fix.

**Secrets** are never returned by a listing or a status route. Private keys
appear only in a client's config, its QR code, the export archive and a backup,
all of which exist to hand them out.
"""


def document(server_url: str, version: str) -> dict:
    """The whole catalog as an OpenAPI 3.1 document.

    `server_url` is this panel's own API root, absolute and including the base
    path, so a document imported into a tool works without being edited first.
    """
    paths: dict[str, dict] = {}
    for op in CATALOG:
        paths.setdefault(f"/{op.path}", {})[op.method] = op.render()

    return {
        "openapi": "3.1.0",
        "info": {
            "title": "AWG Panel API",
            "version": version,
            "summary": "Manage an AmneziaWG server: its clients, its interface and the panel itself.",
            "description": DESCRIPTION,
        },
        "servers": [{"url": server_url, "description": "This panel."}],
        "tags": [{"name": name, "description": note} for name, note in TAGS],
        "components": {
            "securitySchemes": {
                BEARER: {
                    "type": "http",
                    "scheme": "bearer",
                    "description": (
                        "A token issued under API - Authentication. Send it as "
                        "`Authorization: Bearer awgp_...` on every request. Needs no "
                        "CSRF token and leaves no session behind."
                    ),
                },
                COOKIE: {
                    "type": "apiKey",
                    "in": "cookie",
                    "name": "awgsessionid",
                    "description": (
                        "The cookie `POST auth/login` sets. A mutating request carrying it "
                        "must also send `X-CSRFToken`."
                    ),
                },
            }
        },
        # Token or session, unless an operation says otherwise. Stated at the
        # top as well so a tool that ignores per-operation security still
        # prompts for a credential.
        "security": [{BEARER: []}, {COOKIE: []}],
        "paths": paths,
    }
